# Thumbnail: Day 1 (one tree, one chest) vs Day 100 (castle base), heroes rendered with thumb.js (no HUD).
import sys; sys.path.insert(0, '..')
from thumb_common import *
pop = lambda im: ImageEnhance.Contrast(ImageEnhance.Color(im).enhance(1.4)).enhance(1.1)
left = pop(Image.open('hero_day1.jpg').convert('RGB')).crop((420, 0, 1500, 1080)).resize((720, 720), Image.LANCZOS)
right = pop(Image.open('hero_day100.jpg').convert('RGB')).crop((250, 40, 1700, 1084)).resize((1000, 720), Image.LANCZOS)
c = split(left, right, x0=620, slope=.18).convert('RGBA'); L = Image.new('RGBA', (W, H), (0, 0, 0, 0))
v = Image.new('L', (W, H), 0); ImageDraw.Draw(v).ellipse((-220, -180, W + 220, H + 180), fill=255)
dark = Image.new('RGBA', (W, H), (0, 0, 0, 255)); dark.putalpha(Image.eval(v.filter(ImageFilter.GaussianBlur(120)), lambda a: int((255 - a) * .45)))
L.alpha_composite(dark)
text(L, (300, 6), '100 DAYS', 150, '#ffd400', 15)
tag(L, (420, 188), 'SKY ISLAND', 56, (229, 57, 53, 255), 'white', rot=-3)
tag(L, (36, 590), 'DAY 1', 58, (20, 20, 20, 235), '#ffffff', rot=3)
tag(L, (990, 590), 'DAY 100', 58, (255, 212, 0, 255), '#111111', rot=-3)
out = Image.alpha_composite(c, L).convert('RGB'); out.save('thumb_skyisland.jpg', quality=95)
